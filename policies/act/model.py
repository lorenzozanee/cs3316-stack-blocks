"""Evaluate starter ACT checkpoints through the XPolicyLab websocket server."""

from __future__ import annotations

import pickle
from collections import deque
from pathlib import Path

import cv2
import numpy as np
import torch

from XPolicyLab.model_template import ModelTemplate
from XPolicyLab.utils.checkpoint_resolver import resolve_checkpoint_root
from XPolicyLab.utils.process_data import (
    get_robot_action_dim_info,
    pack_robot_state,
    unpack_robot_state,
)
from starter.interfaces import BENCH_NAME, ENV_CFG, EVAL_TASK, GRIPPER_KEYS, HEAD_CAMERA
from starter.policies.act import load_offline_policy


class Model(ModelTemplate):
    """Only head-camera RGB and ee state enter the pretrained policy."""

    def __init__(self, model_cfg):
        for key, expected in (("bench_name", BENCH_NAME), ("task_name", EVAL_TASK),
                              ("env_cfg_type", ENV_CFG), ("action_type", "ee")):
            if model_cfg[key] != expected:
                raise ValueError(f"ACT evaluation requires {key}={expected!r}.")
        policy_dir = Path(__file__).resolve().parent
        checkpoint = resolve_checkpoint_root(
            model_cfg, policy_dir / "checkpoints", policy_dir=policy_dir,
        )
        if not checkpoint.is_file():
            raise ValueError("Pass the path of an ACT .ckpt file, not a run directory.")
        self.device = torch.device(model_cfg["device"])
        self.policy = load_offline_policy(checkpoint, self.device)
        if self.policy.model.camera_names != [HEAD_CAMERA]:
            raise ValueError("ACT evaluation requires the cam_head-only checkpoint.")
        # These files are generated by this project's offline trainer.
        with (checkpoint.parent / "dataset_stats.pkl").open("rb") as stream:
            stats = pickle.load(stream)
        self.stats = {key: np.asarray(stats[key], dtype=np.float32)
                      for key in ("qpos_mean", "qpos_std", "action_mean", "action_std")}
        self.robot_dims = get_robot_action_dim_info(model_cfg["env_cfg_type"])
        self.temporal_agg = bool(model_cfg["temporal_agg"])
        self.chunk_size = self.policy.model.num_queries
        self.reset()

    def reset(self):
        self.observations = {}
        self.histories = {}

    def update_obs(self, obs):
        self.update_obs_batch([obs])

    def update_obs_batch(self, obs_list):
        observations = {}
        for obs in obs_list:
            # The shared server has already decoded this image to RGB.
            color = np.asarray(obs["vision"][HEAD_CAMERA]["color"])
            if color.ndim != 3 or color.shape[2] != 3:
                raise ValueError("cam_head must be a decoded HWC RGB image.")
            image = cv2.resize(color, (640, 480)).astype(np.float32) / 255.0
            qpos = pack_robot_state(obs, "ee", self.robot_dims, source_type="obs")
            qpos = (np.asarray(qpos, dtype=np.float32) - self.stats["qpos_mean"]) / self.stats["qpos_std"]
            observations[int(obs.get("env_idx", 0))] = (qpos, np.moveaxis(image, -1, 0))
        self.observations = observations

    def get_action(self):
        return self.get_action_batch([0])[0]

    @torch.inference_mode()
    def get_action_batch(self, env_idx_list=None):
        indices = list(self.observations) if env_idx_list is None else list(env_idx_list)
        if not indices:
            raise RuntimeError("Update observations before requesting ACT actions.")
        states, images = zip(*(self.observations[int(index)] for index in indices))
        qpos = torch.from_numpy(np.stack(states)).to(self.device)
        image = torch.from_numpy(np.stack(images)[:, None]).to(self.device)
        predictions = self.policy(qpos, image).cpu().numpy()
        chunks = []
        for index, predicted in zip(indices, predictions):
            if self.temporal_agg:
                history = self.histories.setdefault(int(index), deque(maxlen=self.chunk_size))
                history.append(predicted)
                count = len(history)
                # Oldest prediction first, exactly as the upstream ACT weighting.
                aligned = np.stack([chunk[count - 1 - i] for i, chunk in enumerate(history)])
                weights = np.exp(-0.01 * np.arange(count))
                predicted = (aligned * (weights / weights.sum())[:, None]).sum(0, keepdims=True)
            actions = predicted * self.stats["action_std"] + self.stats["action_mean"]
            if not np.isfinite(actions).all():
                raise ValueError("ACT produced a non-finite action.")
            action_chunk = unpack_robot_state(actions.astype(np.float32), "ee", self.robot_dims, source_type="obs")
            for action in action_chunk:
                for key in GRIPPER_KEYS:
                    action[key] = np.clip(action[key], 0.0, 1.0)
            chunks.append(action_chunk)
        return chunks
